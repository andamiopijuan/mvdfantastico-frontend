export function getFilmBySlug(slug: string): Film2026 | undefined {
  return FILMS_2026.find((f) => f.slug === slug);
}

export function getFilmsByCategory(): Map<FilmCategory, Film2026[]> {
  const map = new Map<FilmCategory, Film2026[]>();
  for (const cat of CATEGORY_ORDER) {
    const films = FILMS_2026.filter((f) => f.category === cat);
    if (films.length > 0) map.set(cat, films);
  }
  return map;
}
